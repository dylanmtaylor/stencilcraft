//! Grbl-style G-code export for cutting lasers and plotting routers.
//!
//! Modality: `G21` millimetres, `G90` absolute, feed in mm/min. Each subpath is
//! one cut: rapid (`G0`) to the start, tool/power on, `G1` along the path, off.
//! Laser machines take `M4` (dynamic power) plus an `S` power value in the
//! conventional 0–1000 range; running machines that use `M3`/spindle on/off with
//! Z can be accommodated by profiles later (`docs/gaps.md` 4). Coordinates are
//! absolute millimetres from the sheet origin, exactly where the document says.

use std::fmt::Write as _;

use stencilcraft_doc::Document;
use stencilcraft_geom::path_to_polylines;

#[derive(Debug, thiserror::Error)]
pub enum GcodeError {
    #[error("gcode: {0}")]
    Invalid(String),
    #[error("gcode: {0}")]
    Write(String),
}

/// Output settings; a document-independent knob set the CLI and UI can pass in.
#[derive(Debug, Clone, PartialEq)]
pub struct GcodeSettings {
    /// Feed rate while cutting, millimetres per minute.
    pub feed_mm_per_min: f64,
    /// Laser power for `S`, 0–1000 (Grbl convention).
    pub power: u32,
}

impl Default for GcodeSettings {
    fn default() -> Self {
        Self {
            feed_mm_per_min: 1000.0,
            power: 500,
        }
    }
}

/// Serialise a document to G-code.
pub fn export(doc: &Document, settings: &GcodeSettings) -> Result<String, GcodeError> {
    if !settings.feed_mm_per_min.is_finite() || settings.feed_mm_per_min <= 0.0 {
        return Err(GcodeError::Invalid(format!(
            "feed rate {} mm/min is not a positive finite rate",
            settings.feed_mm_per_min
        )));
    }
    if settings.power > 1000 {
        return Err(GcodeError::Invalid(format!(
            "power {} is outside the 0–1000 range",
            settings.power
        )));
    }
    doc.validate()
        .map_err(|e| GcodeError::Invalid(e.to_string()))?;

    let mut out = String::with_capacity(4096);
    let _ = writeln!(
        out,
        "; generated by stencilcraft ({} shapes, kerf {:.3} mm)",
        doc.shape_count(),
        doc.kerf.width_mm
    );
    let _ = writeln!(out, "G21 ; millimetres");
    let _ = writeln!(out, "G90 ; absolute coordinates");
    let _ = writeln!(out, "G17 ; XY plane");
    let _ = writeln!(out, "M4 S{} ; laser with dynamic power", settings.power);
    for layer in &doc.layers {
        let kind = match layer.kind {
            stencilcraft_doc::CutStyle::Cut => "cut",
            stencilcraft_doc::CutStyle::Engrave => "engrave",
        };
        let _ = writeln!(out, "; layer {} ({kind})", layer.name);
        if !layer.visible {
            let _ = writeln!(out, "; (layer hidden, skipped)");
            continue;
        }
        for shape in &layer.shapes {
            for pl in &path_to_polylines(&shape.path, stencilcraft_geom::DEFAULT_FLATTEN_STEPS) {
                if pl.points.is_empty() {
                    continue;
                }
                emit_polyline(&mut out, pl, settings.feed_mm_per_min)?;
            }
        }
    }
    let _ = writeln!(out, "M5 ; tool off");
    let _ = writeln!(out, "G0 X0 Y0 ; return to origin");
    Ok(out)
}

fn emit_polyline(
    out: &mut String,
    pl: &stencilcraft_geom::Polyline,
    feed: f64,
) -> Result<(), GcodeError> {
    if pl.points.len() < 2 {
        // A single-point subpath is a dot: pulse once, safely, at the point.
        let Some(p) = pl.points.first() else {
            return Ok(());
        };
        emit_travel(out, *p)?;
        emit_dot(out, *p, feed);
        return Ok(());
    }
    if pl.closed {
        // For a closed contour the machine must end where it started: repeat the
        // first point after the rest.
        let mut closed = pl.points.clone();
        if let Some(first) = pl.points.first() {
            closed.push(*first);
        }
        emit_run(out, &closed, feed)
    } else {
        emit_run(out, &pl.points, feed)
    }
}

fn emit_run(out: &mut String, pts: &[kurbo::Point], feed: f64) -> Result<(), GcodeError> {
    let Some(first) = pts.first() else {
        return Ok(());
    };
    emit_travel(out, *first)?;
    for p in &pts[1..] {
        if !p.x.is_finite() || !p.y.is_finite() {
            return Err(GcodeError::Write(
                "gcode: a vertex is not finite".to_string(),
            ));
        }
        let _ = writeln!(out, "G1 X{:.4} Y{:.4} F{:.0}", p.x, p.y, feed);
    }
    Ok(())
}

fn emit_travel(out: &mut String, p: kurbo::Point) -> Result<(), GcodeError> {
    if !p.x.is_finite() || !p.y.is_finite() {
        return Err(GcodeError::Write(
            "gcode: a vertex is not finite".to_string(),
        ));
    }
    let _ = writeln!(out, "G0 X{:.4} Y{:.4}", p.x, p.y);
    Ok(())
}

fn emit_dot(out: &mut String, p: kurbo::Point, feed: f64) {
    // A "dot" is one minimal in-and-out move; keep it on the feed rate.
    let _ = writeln!(out, "G1 X{:.4} Y{:.4} F{:.0}", p.x + 0.001, p.y, feed);
    let _ = writeln!(out, "G1 X{:.4} Y{:.4} F{:.0}", p.x, p.y, feed);
}

#[cfg(test)]
mod tests {
    use super::*;
    use stencilcraft_geom::Point;

    fn line_doc() -> Document {
        let mut doc = Document::default();
        let mut p = kurbo::BezPath::new();
        p.move_to(Point::new(0.0, 0.0));
        p.line_to(Point::new(10.0, 0.0));
        doc.push_shape(0, p, stencilcraft_doc::CutStyle::Cut)
            .unwrap();
        doc
    }

    #[test]
    fn header_and_footer_modality() {
        let g = export(&line_doc(), &GcodeSettings::default()).unwrap();
        assert!(g.contains("G21"));
        assert!(g.contains("G90"));
        assert!(g.contains("M4 S500"));
        assert!(g.contains("M5"));
        assert!(g.starts_with("; generated by stencilcraft"));
    }

    #[test]
    fn travel_then_cut_with_feed() {
        let g = export(&line_doc(), &GcodeSettings::default()).unwrap();
        assert!(g.contains("G0 X0.0000 Y0.0000"), "{g}");
        assert!(g.contains("G1 X10.0000 Y0.0000 F1000"), "{g}");
    }

    #[test]
    fn closed_loops_return_to_start() {
        let mut doc = Document::default();
        let mut p = kurbo::BezPath::new();
        p.move_to(Point::new(0.0, 0.0));
        p.line_to(Point::new(10.0, 0.0));
        p.line_to(Point::new(10.0, 10.0));
        p.close_path();
        doc.push_shape(0, p, stencilcraft_doc::CutStyle::Cut)
            .unwrap();
        let g = export(&doc, &GcodeSettings::default()).unwrap();
        let last_y10 = g.matches("Y0.0000").count();
        assert!(last_y10 >= 2, "must return to start on a closed loop:\n{g}");
    }

    #[test]
    fn bad_feed_rejected() {
        assert!(matches!(
            export(
                &line_doc(),
                &GcodeSettings {
                    feed_mm_per_min: 0.0,
                    power: 100
                }
            ),
            Err(GcodeError::Invalid(_))
        ));
    }

    #[test]
    fn nan_kerf_rejected() {
        let mut doc = Document::default();
        doc.kerf.width_mm = f64::NAN;
        assert!(matches!(
            export(
                &doc,
                &GcodeSettings {
                    feed_mm_per_min: 100.0,
                    power: 100
                }
            ),
            Err(GcodeError::Invalid(_))
        ));
    }
}
