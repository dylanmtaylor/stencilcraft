#!/usr/bin/env bash
# Grant the active local desktop user raw USB access to catalogued cutters.
# Usage: packaging/linux/grant-cutter-access.sh [--print]
# --print shows the generated udev rules without changing the host.
set -euo pipefail

MODE=install
case "${1:-}" in
  --print) MODE=print ;;
  -h|--help) sed -n '2,4p' "$0"; exit 0 ;;
  '') ;;
  *) echo "Unknown option: $1" >&2; exit 2 ;;
esac
if [ "$#" -gt 1 ]; then
  echo 'Expected at most one option' >&2
  exit 2
fi
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CATALOG="$HERE/../../crates/machine/machines.toml"
RULE_NAME=70-stencilcraft-cutters.rules
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
RULE="$WORK/$RULE_NAME"

# Accept only exact catalog USB assignments; never interpolate arbitrary TOML
# text into a root-owned rule. Refuse a malformed assignment or an empty list.
awk '
  /^[[:space:]]*usb[[:space:]]*=/ {
    if ($0 !~ /^[[:space:]]*usb = "[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]:[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]"[[:space:]]*$/) {
      bad=1; exit 1
    }
    split($0, fields, "\""); ids[tolower(fields[2])]=1; count++
  }
  END { if (bad || !count) exit 1; for (id in ids) print id }
' "$CATALOG" | LC_ALL=C sort > "$WORK/ids"
{
  echo '# Generated by StencilCraft grant-cutter-access.sh from machines.toml.'
  echo '# Access follows the active local desktop session (systemd-logind).'
  while IFS=: read -r vendor product; do
    printf 'SUBSYSTEM=="usb", ENV{DEVTYPE}=="usb_device", ATTR{idVendor}=="%s", ATTR{idProduct}=="%s", TAG+="uaccess"\n' "$vendor" "$product"
  done < "$WORK/ids"
} > "$RULE"

if [ "$MODE" = print ]; then
  cat "$RULE"
  exit 0
fi
if [ "$(uname -s)" != Linux ] || ! command -v udevadm >/dev/null; then
  echo 'This script requires Linux with udev and systemd-logind.' >&2
  exit 1
fi
if udevadm verify --help >/dev/null 2>&1; then
  udevadm verify "$RULE"
fi
ROOT=()
if [ "$(id -u)" -ne 0 ]; then
  ROOT=(sudo)
fi
printf 'Installing %s for %s catalogued USB IDs.\n' "$RULE_NAME" "$(wc -l < "$WORK/ids")"
"${ROOT[@]}" install -o root -g root -m 0644 "$RULE" "/etc/udev/rules.d/$RULE_NAME"
"${ROOT[@]}" udevadm control --reload-rules
while IFS=: read -r vendor product; do
  "${ROOT[@]}" udevadm trigger --action=change --subsystem-match=usb \
    --attr-match="idVendor=$vendor" --attr-match="idProduct=$product"
done < "$WORK/ids"
udevadm settle
echo 'Cutter access rules installed. In Make, click Find USB cutters again.'
echo 'If access is still denied, reconnect the cutter and check that your desktop session is active.'
echo 'Flatpak additionally needs --device=usb; this script does not change Flatpak permissions.'
